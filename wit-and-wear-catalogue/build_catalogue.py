#!/usr/bin/env python3
"""Build the static catalogue data and resized mockup images from source files."""

from __future__ import annotations

import argparse
import csv
import json
import re
import shutil
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    Image = None


DEFAULT_CSV = Path(r"C:\Users\hp\Desktop\Projets\Reseaux\liens_produits.csv")
DEFAULT_MOCKUPS = Path(r"C:\Users\hp\Desktop\Projets\POD\a_valider\mockups_gpt")


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def manifest_entries(root: Path) -> dict[str, tuple[Path, dict]]:
    found: dict[str, tuple[Path, dict]] = {}
    for manifest in sorted(root.rglob("manifest.json")):
        try:
            entries = json.loads(manifest.read_text(encoding="utf-8-sig"))
        except (OSError, json.JSONDecodeError) as exc:
            print(f"Skipping unreadable manifest {manifest}: {exc}", file=sys.stderr)
            continue
        if isinstance(entries, dict):
            entries = entries.get("products", entries.get("items", []))
        for entry in (entries if isinstance(entries, list) else []):
            if entry.get("id"):
                found[entry["id"]] = (manifest.parent, entry)
    return found


def image_for(base: Path, entry: dict, design_id: str) -> Path | None:
    for key in ("mockup_A", "mockup", "image", "image_path", "mockup_B"):
        value = entry.get(key)
        if value:
            candidate = base / Path(value)
            if candidate.is_file():
                return candidate
    mockup_dir = base / "mockups"
    for suffix in ("_A", "_B", ""):
        for extension in (".png", ".jpg", ".jpeg", ".webp"):
            candidate = mockup_dir / f"{design_id}{suffix}{extension}"
            if candidate.is_file():
                return candidate
    # Some manifests only identify the design; accept a matching mockup below the batch.
    for candidate in sorted(base.rglob(f"{design_id}*")):
        if candidate.is_file() and "mockup" in candidate.parent.name.lower() and candidate.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp"}:
            return candidate
    return None


def make_jpeg(source: Path, destination: Path) -> None:
    if Image is None:
        raise RuntimeError("Pillow is required to create the 800 px JPEG mockups. Install it with: py -m pip install Pillow")
    with Image.open(source) as original:
        image = original.convert("RGB")
        if image.width > 800:
            height = round(image.height * 800 / image.width)
            image = image.resize((800, height), Image.Resampling.LANCZOS)
        image.save(destination, "JPEG", quality=86, optimize=True, progressive=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV, help="Product links CSV")
    parser.add_argument("--mockups", type=Path, default=DEFAULT_MOCKUPS, help="Root containing dated mockups_gpt manifests")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent, help="Catalogue output directory")
    args = parser.parse_args()

    rows = read_csv(args.csv)
    manifests = manifest_entries(args.mockups)
    image_dir = args.output / "img"
    image_dir.mkdir(parents=True, exist_ok=True)
    products: list[dict] = []
    skipped: list[str] = []

    for row in rows:
        design_id = (row.get("id") or "").strip()
        links = {name: (row.get(name) or "").strip() for name in ("redbubble", "teepublic", "spreadshirt")}
        if not any(links.values()):
            continue
        match = manifests.get(design_id)
        source = image_for(match[0], match[1], design_id) if match else None
        if source is None:
            skipped.append(design_id)
            continue
        filename = re.sub(r"[^A-Za-z0-9_-]", "_", design_id) + ".jpg"
        make_jpeg(source, image_dir / filename)
        manifest_data = match[1]
        niche = (row.get("niche") or row.get("category") or manifest_data.get("niche") or manifest_data.get("category") or "").strip()
        product = {
            "id": design_id,
            "quote": (row.get("quote") or "").strip(),
            "image": f"img/{filename}",
            "links": {key: value for key, value in links.items() if value},
        }
        if niche:
            product["niche"] = niche
        products.append(product)

    js = "// Generated by build_catalogue.py. Edit the CSV/manifests, then rebuild.\n"
    js += "window.CATALOGUE_PRODUCTS = " + json.dumps(products, ensure_ascii=False, indent=2) + ";\n"
    (args.output / "produits.js").write_text(js, encoding="utf-8")
    report = [
        "# Catalogue build report",
        "",
        f"- Products included: {len(products)}",
        f"- Linked designs without an available mockup: {len(skipped)}",
        "- Skipped design IDs: " + (", ".join(skipped) if skipped else "None"),
    ]
    (args.output / "rapport_build.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"Built {len(products)} products; skipped {len(skipped)} linked designs without a mockup.")
    if skipped:
        print("Skipped IDs: " + ", ".join(skipped))
    if not products:
        print("No products were built. Check the CSV and manifest paths.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
